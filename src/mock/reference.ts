export interface ModuleDefinition {
  slug: string;
  title: string;
  description: string;
  domain: string;
  editable: boolean;
  placeholder?: boolean;
  statuses: string[];
}
export interface ModuleGroup {
  title: string;
  ne: string;
  domain: string;
  icon: string;
  modules: ModuleDefinition[];
}
const module = (
  domain: string,
  title: string,
  editable = false,
  placeholder = false,
): ModuleDefinition => ({
  slug: `${domain}/${title
    .toLowerCase()
    .replaceAll("&", "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/-$/, "")}`,
  title,
  description: `Manage and review ${title.toLowerCase()} across Volt OS.`,
  domain,
  editable,
  placeholder,
  statuses: ["Active", "Pending", "Completed", "Draft"],
});
const group = (
  title: string,
  ne: string,
  domain: string,
  icon: string,
  items: string[],
  editable: string[] = [],
  placeholders: string[] = [],
): ModuleGroup => ({
  title,
  ne,
  domain,
  icon,
  modules: items.map((t) => module(domain, t, editable.includes(t), placeholders.includes(t))),
});
